CREATE TABLE IF NOT EXISTS router_ca_key_state (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    router_ca_id BIGINT UNSIGNED NOT NULL,
    key_id VARCHAR(255) NOT NULL,
    key_version VARCHAR(64) NOT NULL,
    key_epoch BIGINT UNSIGNED NOT NULL DEFAULT 0,
    algorithm VARCHAR(64) NOT NULL,
    key_usage VARCHAR(512) NULL,
    lifecycle_state ENUM('provisioned','active','expiring','expired','rotating','revoked','suspended','destroyed') NOT NULL,
    valid_from DATETIME NULL,
    valid_to DATETIME NULL,
    last_rotation_at DATETIME NULL,
    next_rotation_at DATETIME NULL,
    secure_storage_backend VARCHAR(64) NOT NULL,
    secure_storage_reference VARCHAR(512) NOT NULL,
    public_key_fingerprint CHAR(64) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_router_ca_key (router_ca_id, key_id, key_version),
    KEY idx_router_ca_key_rotation (next_rotation_at),
    KEY idx_router_ca_key_lifecycle (lifecycle_state),
    CONSTRAINT fk_router_ca_key_ca FOREIGN KEY (router_ca_id) REFERENCES router_ca(id)
) ENGINE=InnoDB;
