CREATE TABLE IF NOT EXISTS router_ca_provider (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    provider_name VARCHAR(255) NOT NULL,
    provider_type ENUM('manufacturer','isp','public','private','enterprise','other') NOT NULL,
    organization VARCHAR(255) NULL,
    country_code CHAR(2) NULL,
    endpoint VARCHAR(2048) NULL,
    protocol VARCHAR(64) NULL,
    provider_certificate_fingerprint CHAR(128) NULL,
    authentication_mode ENUM('certificate','signature','mutual_tls','manual','other') NOT NULL DEFAULT 'certificate',
    trust_anchor_reference VARCHAR(512) NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    recommended BOOLEAN NOT NULL DEFAULT FALSE,
    priority INT NOT NULL DEFAULT 100,
    last_verified_at DATETIME NULL,
    last_synchronized_at DATETIME NULL,
    next_sync_at DATETIME NULL,
    status ENUM('unknown','active','degraded','expired','revoked','disabled','error') NOT NULL DEFAULT 'unknown',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_router_ca_provider_name (provider_name),
    KEY idx_router_ca_provider_recommended (recommended, enabled),
    KEY idx_router_ca_provider_status (status)
) ENGINE=InnoDB;
