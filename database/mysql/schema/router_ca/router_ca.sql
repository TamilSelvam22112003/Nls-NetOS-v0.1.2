-- NLS Router-CA registry and lifecycle metadata.
-- Secrets/private keys MUST NOT be stored here.

CREATE TABLE IF NOT EXISTS router_ca (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    router_id VARCHAR(128) NOT NULL,
    router_name VARCHAR(255) NULL,
    provider_id BIGINT UNSIGNED NULL,
    ca_name VARCHAR(255) NOT NULL,
    ca_type ENUM('manufacturer','isp','public','private','enterprise','other') NOT NULL,
    ca_endpoint VARCHAR(2048) NULL,
    protocol VARCHAR(64) NULL,
    certificate_serial VARCHAR(512) NULL,
    certificate_fingerprint CHAR(128) NULL,
    certificate_version VARCHAR(64) NULL,
    certificate_not_before DATETIME NULL,
    certificate_not_after DATETIME NULL,
    refresh_before_expiry_seconds INT UNSIGNED NOT NULL DEFAULT 2592000,
    last_verified_at DATETIME NULL,
    last_synchronized_at DATETIME NULL,
    next_refresh_at DATETIME NULL,
    status ENUM('unknown','active','expiring','expired','revoked','disabled','error') NOT NULL DEFAULT 'unknown',
    trust_status ENUM('unknown','trusted','pending','rejected','revoked') NOT NULL DEFAULT 'unknown',
    key_reference VARCHAR(512) NULL,
    key_version VARCHAR(64) NULL,
    key_epoch BIGINT UNSIGNED NULL,
    key_valid_from DATETIME NULL,
    key_valid_to DATETIME NULL,
    key_status ENUM('unknown','active','expiring','expired','revoked','rotating','suspended') NOT NULL DEFAULT 'unknown',
    secure_storage_backend VARCHAR(64) NULL,
    secure_storage_reference VARCHAR(512) NULL,
    boot_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    auto_refresh_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    auto_rotate_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    last_error_code VARCHAR(128) NULL,
    last_error_message VARCHAR(1024) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_router_ca_router_provider (router_id, provider_id, ca_name),
    KEY idx_router_ca_status (status),
    KEY idx_router_ca_expiry (certificate_not_after),
    KEY idx_router_ca_next_refresh (next_refresh_at),
    KEY idx_router_ca_key_status (key_status)
) ENGINE=InnoDB;
