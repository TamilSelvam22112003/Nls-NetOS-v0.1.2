CREATE TABLE IF NOT EXISTS router_ca_certificate (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    router_ca_id BIGINT UNSIGNED NOT NULL,
    certificate_serial VARCHAR(512) NOT NULL,
    subject VARCHAR(2048) NOT NULL,
    issuer VARCHAR(2048) NOT NULL,
    fingerprint_sha256 CHAR(64) NOT NULL,
    public_key_algorithm VARCHAR(64) NOT NULL,
    public_key_bits INT UNSIGNED NULL,
    signature_algorithm VARCHAR(128) NULL,
    not_before DATETIME NOT NULL,
    not_after DATETIME NOT NULL,
    revoked BOOLEAN NOT NULL DEFAULT FALSE,
    revocation_checked_at DATETIME NULL,
    status ENUM('active','expiring','expired','revoked','invalid','superseded') NOT NULL DEFAULT 'active',
    secure_storage_reference VARCHAR(512) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_router_ca_certificate_fp (fingerprint_sha256),
    KEY idx_router_ca_certificate_expiry (not_after),
    KEY idx_router_ca_certificate_status (status),
    CONSTRAINT fk_router_ca_certificate_ca FOREIGN KEY (router_ca_id) REFERENCES router_ca(id)
) ENGINE=InnoDB;
