-- NLS/OSPF Identity Comparison
CREATE TABLE IF NOT EXISTS identity_comparison (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    session_id BIGINT UNSIGNED NOT NULL,
    observation_id BIGINT UNSIGNED NULL,
    ca_response_id BIGINT UNSIGNED NULL,
    router_id_match BOOLEAN NOT NULL DEFAULT FALSE,
    ip_match BOOLEAN NOT NULL DEFAULT FALSE,
    public_key_id_match BOOLEAN NOT NULL DEFAULT FALSE,
    public_key_algorithm_match BOOLEAN NOT NULL DEFAULT FALSE,
    public_key_size_match BOOLEAN NOT NULL DEFAULT FALSE,
    public_key_version_match BOOLEAN NOT NULL DEFAULT FALSE,
    public_key_fingerprint_match BOOLEAN NOT NULL DEFAULT FALSE,
    certificate_serial_match BOOLEAN NOT NULL DEFAULT FALSE,
    certificate_fingerprint_match BOOLEAN NOT NULL DEFAULT FALSE,
    certificate_valid BOOLEAN NOT NULL DEFAULT FALSE,
    certificate_revoked BOOLEAN NOT NULL DEFAULT FALSE,
    key_active BOOLEAN NOT NULL DEFAULT FALSE,
    signature_valid BOOLEAN NOT NULL DEFAULT FALSE,
    nonce_valid BOOLEAN NOT NULL DEFAULT FALSE,
    hop_path_valid BOOLEAN NOT NULL DEFAULT FALSE,
    overall_match BOOLEAN NOT NULL DEFAULT FALSE,
    mismatch_count INT UNSIGNED NOT NULL DEFAULT 0,
    mismatch_reason TEXT NULL,
    compared_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    KEY idx_identity_comparison_session (session_id),
    CONSTRAINT fk_identity_comparison_session FOREIGN KEY (session_id) REFERENCES verification_session(id),
    CONSTRAINT fk_identity_comparison_observation FOREIGN KEY (observation_id) REFERENCES neighbor_observation(id),
    CONSTRAINT fk_identity_comparison_ca_response FOREIGN KEY (ca_response_id) REFERENCES router_ca_response(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
