-- NLS/OSPF Router-CA Verification Response
CREATE TABLE IF NOT EXISTS router_ca_response (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    session_id BIGINT UNSIGNED NOT NULL,
    request_id BIGINT UNSIGNED NULL,
    router_id VARCHAR(64) NOT NULL,
    router_ip VARCHAR(64) NULL,
    router_version VARCHAR(64) NULL,
    public_key_id VARCHAR(128) NULL,
    public_key_algorithm VARCHAR(32) NULL,
    public_key_size SMALLINT UNSIGNED NULL,
    public_key_version VARCHAR(64) NULL,
    public_key_fingerprint CHAR(64) NULL,
    certificate_serial VARCHAR(128) NULL,
    certificate_fingerprint CHAR(64) NULL,
    certificate_status VARCHAR(32) NULL,
    certificate_valid_from DATETIME(6) NULL,
    certificate_valid_until DATETIME(6) NULL,
    challenge_nonce VARBINARY(64) NULL,
    ca_signature MEDIUMBLOB NULL,
    response_status VARCHAR(32) NOT NULL DEFAULT 'RECEIVED',
    received_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    KEY idx_router_ca_response_session (session_id),
    KEY idx_router_ca_response_request (request_id),
    KEY idx_router_ca_response_router (router_id, router_ip),
    CONSTRAINT fk_router_ca_response_session FOREIGN KEY (session_id) REFERENCES verification_session(id),
    CONSTRAINT fk_router_ca_response_request FOREIGN KEY (request_id) REFERENCES verification_request(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
