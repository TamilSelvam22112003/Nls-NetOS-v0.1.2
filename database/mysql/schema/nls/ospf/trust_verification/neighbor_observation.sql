-- NLS/OSPF Neighbor Identity Observation
CREATE TABLE IF NOT EXISTS neighbor_observation (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    session_id BIGINT UNSIGNED NOT NULL,
    neighbor_router_id VARCHAR(64) NULL,
    neighbor_ip VARCHAR(64) NULL,
    router_version VARCHAR(64) NULL,
    local_interface_name VARCHAR(64) NULL,
    local_interface_index INT UNSIGNED NULL,
    local_port_number INT UNSIGNED NULL,
    remote_interface_name VARCHAR(64) NULL,
    remote_interface_index INT UNSIGNED NULL,
    remote_port_number INT UNSIGNED NULL,
    mac_address VARCHAR(32) NULL,
    public_key_id VARCHAR(128) NULL,
    public_key_algorithm VARCHAR(32) NULL,
    public_key_size SMALLINT UNSIGNED NULL,
    public_key_version VARCHAR(64) NULL,
    public_key_fingerprint CHAR(64) NULL,
    certificate_serial VARCHAR(128) NULL,
    certificate_fingerprint CHAR(64) NULL,
    certificate_material MEDIUMBLOB NULL,
    signature_algorithm VARCHAR(64) NULL,
    identity_signature MEDIUMBLOB NULL,
    challenge_nonce VARBINARY(64) NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'RECEIVED',
    observed_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    KEY idx_neighbor_observation_session (session_id),
    KEY idx_neighbor_observation_identity (neighbor_router_id, neighbor_ip),
    CONSTRAINT fk_neighbor_observation_session FOREIGN KEY (session_id) REFERENCES verification_session(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
